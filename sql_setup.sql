BEGIN;

DROP TABLE IF EXISTS amir_catalogo_cuentas CASCADE;
DROP TABLE IF EXISTS amir_polizas CASCADE;
DROP TABLE IF EXISTS amir_polizas_detalles CASCADE;

CREATE TABLE amir_catalogo_cuentas (
  id SERIAL PRIMARY KEY,
  codigo TEXT UNIQUE NOT NULL,
  nombre TEXT NOT NULL,
  tipo TEXT NOT NULL,
  nivel INT,
  nif TEXT,
  agrupador_sat NUMERIC,
  created_at TIMESTAMP DEFAULT NOW()
);

CREATE TABLE amir_polizas (
  id SERIAL PRIMARY KEY,
  fecha DATE NOT NULL,
  tipo_poliza TEXT NOT NULL,
  numero TEXT,
  concepto TEXT,
  created_by UUID,
  created_at TIMESTAMP DEFAULT NOW(),
  CONSTRAINT fk_created_by FOREIGN KEY (created_by) REFERENCES auth.users(id)
);

CREATE TABLE amir_polizas_detalles (
  id SERIAL PRIMARY KEY,
  poliza_id INT NOT NULL REFERENCES amir_polizas(id) ON DELETE CASCADE,
  cuenta_id INT NOT NULL REFERENCES amir_catalogo_cuentas(id),
  debe NUMERIC(15,2) DEFAULT 0,
  haber NUMERIC(15,2) DEFAULT 0,
  created_at TIMESTAMP DEFAULT NOW()
);

